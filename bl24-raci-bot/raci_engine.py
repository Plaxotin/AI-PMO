"""Движок генерации RACI-матрицы по методологии PMBOK.

Поток: описание проекта -> Kimi -> JSON RACI -> валидация правил PMBOK.
Без KIMI_API_KEY работает демо-режим (встроенный пример MES).
"""
from __future__ import annotations

import kimi_client

LETTERS = ("R", "A", "C", "I")

SYSTEM_PROMPT = """Ты — методолог управления проектами по стандарту PMBOK (PMI).
Формируешь RACI-матрицы (Responsible, Accountable, Consulted, Informed) для проектов в российских компаниях.

Правила RACI по PMBOK:
- R (Responsible / Исполнитель) — выполняет работу; на активность может быть несколько R.
- A (Accountable / Ответственный) — отвечает за результат и принимает решения; СТРОГО ОДИН A на каждую активность.
- C (Consulted / Консультируемый) — двусторонняя коммуникация, экспертиза до выполнения.
- I (Informed / Информируемый) — одностороннее уведомление о ходе/результате.
- Роли — это роли, а не ФИО (например: «Спонсор проекта», «Руководитель проекта», «Команда разработки»).
- Активности группируются по фазам жизненного цикла проекта (инициация, планирование, исполнение, контроль, закрытие), детализируются под тип проекта.

Отвечай СТРОГО в JSON на русском языке по схеме:
{
  "project_name": "строка",
  "project_goal": "строка",
  "project_scope": "строка",
  "roles": ["роль 1", "роль 2", ...],
  "activities": [
    {"phase": "фаза", "name": "активность", "assignments": {"роль 1": "R", "роль 2": "A"}}
  ],
  "notes": ["допущение/пояснение по назначениям 1", ...]
}
Требования: 8–20 активностей; 4–12 ролей; assignments — только для осмысленных ролей активности,
значения строго из {"R","A","C","I"}; ровно один "A" и минимум один "R" на активность.
Поле notes — 3–8 допущений, принятых при назначении ролей (как в образце PMI)."""


def build_messages(description: str, mode: str) -> list[dict]:
    style = (
        "Сгенерируй матрицу быстро и лаконично: типовые фазы и роли, минимум пояснений."
        if mode == "fast"
        else "Сгенерируй матрицу с подробными рекомендациями: обоснуй выбор ролей в notes, "
             "добавь типичные для такого проекта активности и контрольные точки."
    )
    user = (
        "Создай RACI-матрицу для проекта.\n\n"
        f"Описание проекта от пользователя:\n{description}\n\n"
        f"Режим: {style}"
    )
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user},
    ]


def validate(data: dict) -> list[str]:
    """Проверка правил PMBOK. Возвращает список нарушений (пустой = всё ок)."""
    issues: list[str] = []
    roles = data.get("roles") or []
    activities = data.get("activities") or []
    if not roles:
        issues.append("пустой список ролей")
    if not (4 <= len(activities) <= 30):
        issues.append(f"активностей {len(activities)} (нужно 4–30)")
    known = set(roles)
    for act in activities:
        name = act.get("name", "?")
        assign = act.get("assignments") or {}
        bad_letters = set(assign.values()) - set(LETTERS)
        if bad_letters:
            issues.append(f"«{name}»: недопустимые буквы {sorted(bad_letters)}")
        unknown = set(assign) - known
        if unknown:
            issues.append(f"«{name}»: неизвестные роли {sorted(unknown)}")
        a_count = sum(1 for v in assign.values() if v == "A")
        if a_count != 1:
            issues.append(f"«{name}»: ровно один A, фактически {a_count}")
        if "R" not in assign.values():
            issues.append(f"«{name}»: нет ни одного R")
    return issues


def repair(data: dict, issues: list[str], description: str) -> dict:
    """Один повторный запрос к LLM с перечнем нарушений для исправления."""
    messages = build_messages(description, mode="fast")
    messages.append({
        "role": "user",
        "content": (
            "Предыдущий результат нарушил правила RACI:\n- "
            + "\n- ".join(issues)
            + "\n\nИсправь и верни полный JSON заново, строго по правилам."
        ),
    })
    return kimi_client.chat_json(messages)


def generate(description: str, mode: str = "guided") -> tuple[dict, list[str]]:
    """Генерация RACI. Возвращает (data, issues_after_validation)."""
    if not kimi_client.API_KEY:
        return demo_data(), []
    data = kimi_client.chat_json(build_messages(description, mode))
    issues = validate(data)
    if issues:
        data = repair(data, issues, description)
        issues = validate(data)
    return data, issues


